create extension if not exists "pgcrypto";

create sequence public.website_order_number_seq start with 1001;

create type public.website_order_status as enum (
  'new',
  'confirmed',
  'paid',
  'completed',
  'cancelled'
);

create table public.orders (
  id uuid primary key default gen_random_uuid(),
  public_number bigint not null unique default nextval('public.website_order_number_seq'),
  idempotency_key uuid not null unique,
  customer_name text not null check (char_length(customer_name) between 1 and 100),
  whatsapp_phone text not null check (whatsapp_phone ~ '^\\+947[0-9]{8}$'),
  product_total_lkr integer not null check (product_total_lkr > 0),
  delivery_charge_lkr integer check (delivery_charge_lkr >= 0),
  final_total_lkr integer generated always as (
    case
      when delivery_charge_lkr is null then null
      else product_total_lkr + delivery_charge_lkr
    end
  ) stored,
  status public.website_order_status not null default 'new',
  private_note text,
  created_at timestamptz not null default timezone('utc', now()),
  updated_at timestamptz not null default timezone('utc', now())
);

create table public.order_items (
  id uuid primary key default gen_random_uuid(),
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id text not null,
  product_slug text not null,
  product_title text not null,
  unit_price_lkr integer not null check (unit_price_lkr > 0),
  quantity integer not null check (quantity >= 6),
  line_total_lkr integer not null check (line_total_lkr = unit_price_lkr * quantity),
  created_at timestamptz not null default timezone('utc', now())
);

create table public.order_submission_attempts (
  id bigint generated by default as identity primary key,
  identity_hash text not null,
  created_at timestamptz not null default timezone('utc', now())
);

create index order_submission_attempts_recent_idx
  on public.order_submission_attempts(identity_hash, created_at desc);

alter table public.orders enable row level security;
alter table public.order_items enable row level security;
alter table public.order_submission_attempts enable row level security;

revoke all on public.orders from anon, authenticated;
revoke all on public.order_items from anon, authenticated;
revoke all on public.order_submission_attempts from anon, authenticated;
revoke all on sequence public.website_order_number_seq from anon, authenticated;
revoke all on sequence public.order_submission_attempts_id_seq from anon, authenticated;

create or replace function public.set_website_order_updated_at()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.updated_at = timezone('utc', now());
  return new;
end;
$$;

create trigger set_website_order_updated_at
before update on public.orders
for each row
execute function public.set_website_order_updated_at();

create or replace function public.create_website_order(
  p_idempotency_key uuid,
  p_customer_name text,
  p_whatsapp_phone text,
  p_identity_hash text,
  p_items jsonb
)
returns table (
  id uuid,
  public_number bigint,
  product_total_lkr integer,
  created_at timestamptz,
  duplicate boolean
)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_existing public.orders%rowtype;
  v_order public.orders%rowtype;
  v_item jsonb;
  v_quantity numeric;
  v_unit_price numeric;
  v_total bigint := 0;
  v_recent_attempts integer;
begin
  select o.*
  into v_existing
  from public.orders as o
  where o.idempotency_key = p_idempotency_key;

  if found then
    return query
    select
      v_existing.id,
      v_existing.public_number,
      v_existing.product_total_lkr,
      v_existing.created_at,
      true;
    return;
  end if;

  perform pg_advisory_xact_lock(hashtextextended(p_idempotency_key::text, 0));

  select o.*
  into v_existing
  from public.orders as o
  where o.idempotency_key = p_idempotency_key;

  if found then
    return query
    select
      v_existing.id,
      v_existing.public_number,
      v_existing.product_total_lkr,
      v_existing.created_at,
      true;
    return;
  end if;

  if p_customer_name is null
    or char_length(btrim(p_customer_name)) not between 1 and 100 then
    raise exception using message = 'invalid_customer_name', errcode = 'P0001';
  end if;

  if p_whatsapp_phone is null
    or p_whatsapp_phone !~ '^\\+947[0-9]{8}$' then
    raise exception using message = 'invalid_whatsapp_phone', errcode = 'P0001';
  end if;

  if p_identity_hash is null or char_length(btrim(p_identity_hash)) < 32 then
    raise exception using message = 'invalid_identity_hash', errcode = 'P0001';
  end if;

  if p_items is null
    or jsonb_typeof(p_items) <> 'array'
    or jsonb_array_length(p_items) = 0 then
    raise exception using message = 'invalid_order_items', errcode = 'P0001';
  end if;

  for v_item in
    select value from jsonb_array_elements(p_items)
  loop
    if jsonb_typeof(v_item) <> 'object'
      or nullif(btrim(v_item->>'productId'), '') is null
      or nullif(btrim(v_item->>'productSlug'), '') is null
      or nullif(btrim(v_item->>'productTitle'), '') is null
      or jsonb_typeof(v_item->'quantity') <> 'number'
      or jsonb_typeof(v_item->'unitPriceLkr') <> 'number' then
      raise exception using message = 'invalid_order_items', errcode = 'P0001';
    end if;

    begin
      v_quantity := (v_item->>'quantity')::numeric;
      v_unit_price := (v_item->>'unitPriceLkr')::numeric;
    exception
      when others then
        raise exception using message = 'invalid_order_items', errcode = 'P0001';
    end;

    if v_quantity <> trunc(v_quantity)
      or v_quantity < 6
      or v_quantity > 2147483647
      or v_unit_price <> trunc(v_unit_price)
      or v_unit_price <= 0
      or v_unit_price > 2147483647 then
      raise exception using message = 'invalid_order_items', errcode = 'P0001';
    end if;

    v_total := v_total + (v_quantity::bigint * v_unit_price::bigint);
    if v_total > 2147483647 then
      raise exception using message = 'order_total_too_large', errcode = 'P0001';
    end if;
  end loop;

  perform pg_advisory_xact_lock(hashtextextended(p_identity_hash, 0));

  delete from public.order_submission_attempts
  where identity_hash = p_identity_hash
    and created_at < timezone('utc', now()) - interval '7 days';

  select count(*)
  into v_recent_attempts
  from public.order_submission_attempts
  where identity_hash = p_identity_hash
    and created_at >= timezone('utc', now()) - interval '15 minutes';

  if v_recent_attempts >= 5 then
    raise exception using message = 'order_rate_limited', errcode = 'P0001';
  end if;

  insert into public.order_submission_attempts (identity_hash)
  values (p_identity_hash);

  insert into public.orders (
    idempotency_key,
    customer_name,
    whatsapp_phone,
    product_total_lkr
  )
  values (
    p_idempotency_key,
    btrim(p_customer_name),
    p_whatsapp_phone,
    v_total::integer
  )
  returning * into v_order;

  for v_item in
    select value from jsonb_array_elements(p_items)
  loop
    insert into public.order_items (
      order_id,
      product_id,
      product_slug,
      product_title,
      unit_price_lkr,
      quantity,
      line_total_lkr
    )
    values (
      v_order.id,
      btrim(v_item->>'productId'),
      btrim(v_item->>'productSlug'),
      btrim(v_item->>'productTitle'),
      (v_item->>'unitPriceLkr')::integer,
      (v_item->>'quantity')::integer,
      (v_item->>'unitPriceLkr')::integer * (v_item->>'quantity')::integer
    );
  end loop;

  return query
  select
    v_order.id,
    v_order.public_number,
    v_order.product_total_lkr,
    v_order.created_at,
    false;
end;
$$;

revoke execute on function public.create_website_order(uuid, text, text, text, jsonb)
from public, anon, authenticated;

grant execute on function public.create_website_order(uuid, text, text, text, jsonb)
to service_role;
